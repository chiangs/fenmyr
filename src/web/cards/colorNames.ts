export function colorName(hex) {
  const rgb = h => [1, 3, 5].map(i => parseInt(h.slice(i, i + 2), 16)),
    [r, g, b] = rgb(hex);
  let best = 'Colour',
    d = Infinity;
  for (const [n, h] of Object.entries(NAMED)) {
    const [r2, g2, b2] = rgb(h),
      rm = (r + r2) / 2,
      dd = (2 + rm / 256) * (r - r2) ** 2 + 4 * (g - g2) ** 2 + (2 + (255 - rm) / 256) * (b - b2) ** 2;
    if (dd < d) {
      d = dd;
      best = n;
    }
  }
  return best;
}
