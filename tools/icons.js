// Builds web/icons/pack.js: the icons the app asks for, in both weights, from the chosen icon pack (see tools/icons/set.js)
// plus Myra's own (tools/icons/custom.js).
//   npm run icons          (after `npm install`, which brings the pack)
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const set = require('./icons/set'), custom = require('./icons/custom');
const PACK = path.join(ROOT, 'node_modules', set.pack.package);

// a pack file is one <svg>: keep what's inside it. Duotone files mark their tinted layer with opacity="0.2": that becomes class t.
const inner = f => fs.readFileSync(f, 'utf8').replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s+opacity="0\.2"/g, ' class="t"').replace(/\s+fill="currentColor"/g, '').replace(/\n/g, '').trim();
const file = (weight, name) => path.join(PACK, 'assets', weight, weight === 'regular' ? `${name}.svg` : `${name}-${weight}.svg`);

const icons = {}, missing = [];
// the picker's names: normalise the bare / pair forms into [name, packName, keywords]
const pick = set.pickable.map(x => Array.isArray(x) ? [x[0], x[1] || x[0], x[2] || ''] : [x, x, '']);
const all = [...set.icons];
for (const [n, pn, kw] of pick) { const e = all.find(a => a[0] === n); if (e) { if (kw) e[2] = (e[2] || '') + ' ' + kw; } else all.push([n, pn, kw]); }
const pickNames = new Map(pick.map((p, i) => [p[0], i + 1]));
for (const [name, packName, kw] of all) {
  const r = file('regular', packName), d = file('duotone', packName);
  if (!fs.existsSync(r) || !fs.existsSync(d)) { missing.push(`${name} → ${packName}`); continue; }
  icons[name] = { r: inner(r), d: inner(d), kw: [name.replace(/-/g, ' '), packName.replace(/-/g, ' '), kw || ''].join(' ').trim(), ...(pickNames.has(name) ? { p: pickNames.get(name) } : {}) };
}
if (missing.length) { console.error('The pack has no icon for:\n  ' + missing.join('\n  ')); process.exit(1); }
for (const [name, c] of Object.entries(custom)) icons[name] = { r: c.r, d: c.d, kw: (name.replace(/-/g, ' ') + ' ' + (c.kw || '')).trim() };
const pickable = Object.values(icons).filter(i => i.p).length;

const out = `// Generated by tools/icons.js: the icons the app asks for, in both weights (${set.pack.name}, plus Myra's own).\nwindow.MYRA_ICON_PACK = ${JSON.stringify({ id: set.pack.id, name: set.pack.name, icons })};\n`;
fs.writeFileSync(path.join(ROOT, 'web', 'icons', 'pack.js'), out);
// the names Myra may use for wireframe icons (linux/prompts.js tells her this list)
fs.writeFileSync(path.join(ROOT, 'linux', 'icon-names.json'), JSON.stringify(Object.entries(icons).filter(([, e]) => e.p).sort((a, b) => a[1].p - b[1].p).map(([n]) => n)) + '\n');
console.log(`${Object.keys(icons).length} icons, ${pickable} in the picker (${all.length} from ${set.pack.name}, ${Object.keys(custom).length} Myra's own) → web/icons/pack.js, ${(out.length / 1024).toFixed(0)} KB`);
