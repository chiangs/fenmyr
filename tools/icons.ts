// Builds web/icons/pack.js (every icon the app asks for, in both weights) and src/host/icon-names.json
// (the names Myra may use in wireframes) from the pack named in tools/icons/set.ts plus Myra's own icons.
import fs from 'node:fs';
import path from 'node:path';
import { custom } from './icons/custom.ts';
import { type IconEntry, pack, icons as packIcons, pickable } from './icons/set.ts';

type Icon = { r: string; t?: string; d?: string; kw: string; p?: number };

const ROOT = path.resolve(import.meta.dirname, '..');
const PACK = path.join(ROOT, 'node_modules', pack.package);

// a pack file is one <svg>: keep what is inside it; duotone files mark their tinted layer with opacity="0.2", which becomes class t
const inner = (file: string) =>
  fs
    .readFileSync(file, 'utf8')
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/\s+opacity="0\.2"/g, ' class="t"')
    .replace(/\s+fill="currentColor"/g, '')
    .replace(/\n/g, '')
    .trim();
const file = (weight: 'regular' | 'duotone', name: string) =>
  path.join(PACK, 'assets', weight, weight === 'regular' ? `${name}.svg` : `${name}-${weight}.svg`);
const words = (name: string) => name.replace(/-/g, ' ');

const picks: IconEntry[] = pickable.map(x => (Array.isArray(x) ? x : [x, x]));
const all: IconEntry[] = packIcons.map(e => [...e]);
for (const [name, packName, kw] of picks) {
  const known = all.find(a => a[0] === name);
  if (!known) all.push([name, packName, kw ?? '']);
  else if (kw) known[2] = `${known[2] ?? ''} ${kw}`;
}
const pickOrder = new Map(picks.map(([name], i) => [name, i + 1]));

const icons: Record<string, Icon> = {};
const missing: string[] = [];
for (const [name, packName, kw] of all) {
  const regular = file('regular', packName);
  const duotone = file('duotone', packName);
  if (!fs.existsSync(regular) || !fs.existsSync(duotone)) {
    missing.push(`${name} → ${packName}`);
    continue;
  }
  const r = inner(regular);
  const d = inner(duotone);
  // most duotone drawings are the regular outline with a tint layer in front: keep only the tint (the app puts them together)
  const tint = d.endsWith(r) ? { t: d.slice(0, d.length - r.length) } : { d };
  const p = pickOrder.get(name);
  icons[name] = { r, ...tint, kw: [words(name), words(packName), kw ?? ''].join(' ').trim(), ...(p ? { p } : {}) };
}
if (missing.length) {
  console.error(`The pack has no icon for:\n  ${missing.join('\n  ')}`);
  process.exit(1);
}
for (const [name, c] of Object.entries(custom)) icons[name] = { r: c.r, d: c.d, kw: `${words(name)} ${c.kw}`.trim() };

const picked = Object.entries(icons)
  .flatMap(([name, e]) => (e.p ? [[name, e.p] as const] : []))
  .sort((a, b) => a[1] - b[1]);
const packData = JSON.stringify({ id: pack.id, name: pack.name, icons });
const out = `// Generated by tools/icons.ts: the icons the app asks for, in both weights (${pack.name}, plus Myra's own).\nwindow.FENMYR_ICON_PACK = ${packData};\n`;
fs.writeFileSync(path.join(ROOT, 'web', 'icons', 'pack.js'), out);
fs.writeFileSync(
  path.join(ROOT, 'src', 'host', 'icon-names.json'),
  `${JSON.stringify(picked.map(([name]) => name))}\n`,
);
const kb = (out.length / 1024).toFixed(0);
console.log(
  `${Object.keys(icons).length} icons, ${picked.length} in the picker (${all.length} from ${pack.name}, ${Object.keys(custom).length} Myra's own) → web/icons/pack.js, ${kb} KB`,
);
